@pytest.mark.asyncio
async def test_get_profit_events_with_data():
    """Test getting profit events after a wallet is collected and simulated."""
    wallet_name = "event_wallet_1"
    async with AsyncClient(app=app, base_url="http://test") as ac:
        await ac.post("/collect_wallet", json={"wallet": wallet_name})
        # Wait for billion_cycle to potentially generate some events.
        # This makes the test dependent on timing, which is not ideal but necessary
        # for testing the side effects of the async task in this setup.
        # A very short sleep to allow at least one cycle iteration if possible.
        # The actual profit generation part of billion_cycle has multiple sleeps.
        # We'll check for the wallet's registration and then if any events appear after a longer delay.

        # Give a bit more time for the first profit event to be generated by billion_cycle
        # Original sleeps in billion_cycle: randint(2,5) then 2. So minimum 4 seconds.
        # This is too long for a unit test. We are testing the endpoint, and assuming billion_cycle works.
        # For a true integration test of this, we'd wait longer.
        # Here, we'll manually add a dummy event to test the endpoint's retrieval logic.
        profit_events[wallet_name] = [{"id": "test_evt_1", "amount": 100, "sent": True}]

        response = await ac.get(f"/profit_events?wallet={wallet_name}")

    assert response.status_code == 200
    data = response.json()
    assert len(data["profitEvents"]) == 1
    assert data["profitEvents"][0]["id"] == "test_evt_1"

