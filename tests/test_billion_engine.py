@pytest.mark.asyncio
async def test_status_with_data():
    """Test the status endpoint after wallets are registered."""
    wallet_name = "status_wallet_1"
    async with AsyncClient(app=app, base_url="http://test") as ac:
        await ac.post("/collect_wallet", json={"wallet": wallet_name})
        # Manually add some data to simulate state for testing the status endpoint directly
        profit_events[wallet_name] = [{"id": "status_evt_1", "amount": 200, "sent": False}]
        # wallet_scaling_factors is set by collect_wallet

        response = await ac.get("/status")

    assert response.status_code == 200
    data = response.json()
    assert wallet_name in data["wallets"]
    assert data["wallet_scaling_factors"][wallet_name] == 1.0
    assert len(data["profit_events"][wallet_name]) == 1
    assert data["profit_events"][wallet_name][0]["id"] == "status_evt_1"

