@pytest.mark.asyncio
async def test_collect_wallet_new():
    """Test collecting a new wallet."""
    async with AsyncClient(app=app, base_url="http://test") as ac:
        response = await ac.post("/collect_wallet", json={"wallet": "test_wallet_1"})
    assert response.status_code == 200
    data = response.json()
    assert data["status"] == "registered"
    assert data["wallet"] == "test_wallet_1"
    assert "test_wallet_1" in wallets
    assert "test_wallet_1" in wallet_scaling_factors
    assert wallet_scaling_factors["test_wallet_1"] == 1.0

    # Allow some time for the billion_cycle to start and generate an event
    await asyncio.sleep(0.1) # Reduced sleep for faster tests; may need adjustment

